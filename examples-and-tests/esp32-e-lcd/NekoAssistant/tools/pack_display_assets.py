#!/usr/bin/env python3
"""Pack ImageGen's original atlas and the licensed Orbitron font for a 1-bit LCD.

This importer does format conversion, fixed-cell extraction and deterministic
ordered dithering; the character artwork itself is the original generated PNG.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import io

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'assets'
BAYER = ((0, 8, 2, 10), (12, 4, 14, 6), (3, 11, 1, 9), (15, 7, 13, 5))


def binary(im, ordered=False):
    gray = im.convert('L')
    if not ordered:
        return gray.point(lambda p: 255 if p >= 128 else 0, mode='1')
    out = Image.new('1', gray.size, 1)
    for y in range(gray.height):
        for x in range(gray.width):
            threshold = (BAYER[y % 4][x % 4] + .5) * 16
            out.putpixel((x, y), 255 if gray.getpixel((x, y)) >= threshold else 0)
    return out


def xbm(im):
    assert im.width % 8 == 0
    return bytes(sum((im.getpixel((x + bit, y)) == 0) << bit for bit in range(8))
                 for y in range(im.height) for x in range(0, im.width, 8))


def array(name, data):
    lines = [f'inline const uint8_t {name}[] PROGMEM = {{']
    for start in range(0, len(data), 24):
        lines.append('  ' + ','.join(f'0x{x:02x}' for x in data[start:start + 24]) + ',')
    return '\n'.join(lines + ['};', ''])


def prelude(namespace):
    return f'''// Generated by tools/pack_display_assets.py. Do not hand-edit.
#pragma once
#include <cstdint>
#if defined(ARDUINO)
#include <Arduino.h>
#else
#ifndef PROGMEM
#define PROGMEM
#endif
#endif
namespace {namespace} {{
'''


def pets():
    source = Image.open(ASSETS / 'pixel-neko/source-atlas.png').convert('L')
    assert source.size == (1536, 1024)
    header = prelude('NekoPetAssets') + 'constexpr unsigned Count = 1;\n'
    all_frames = {}
    for size in (64, 128, 160, 192, 224):
        frames = []
        for index in range(1):
            col, row = index % 4, index // 4
            cell = source.crop((col * 384, row * 512, (col + 1) * 384, (row + 1) * 512))
            # All cells share the same crop and baseline. Padding outside a cell is white.
            crop = Image.new('L', (408, 408), 255)
            crop.paste(cell.crop((0, 42, 384, 450)), (12, 0))
            im = binary(crop.resize((size, size), Image.Resampling.LANCZOS), ordered=True)
            frames.append(im)
            header += array(f'Frame{size}_{index}', xbm(im))
        header += f'constexpr unsigned Size{size} = {size};\n'
        header += f'inline const uint8_t *const Frames{size}[Count] = {{' + ','.join(f'Frame{size}_{i}' for i in range(1)) + '};\n'
        all_frames[size] = frames
    (ROOT / 'NekoPetAssets.h').write_text(header + '}\n')
    all_frames[160][0].save(ASSETS / 'pixel-neko/pet-atlas.png', optimize=True)
    all_frames[160][0].save(ASSETS / 'pixel-neko/preview.png')



def clocks():
    font = ImageFont.truetype(str(ASSETS / 'orbitron/Orbitron.ttf'), 512)
    if hasattr(font, 'set_variation_by_axes'):
        font.set_variation_by_axes([650])
    chars = '0123456789-'
    top = min(font.getbbox(c)[1] for c in '0123456789')
    bottom = max(font.getbbox(c)[3] for c in '0123456789')
    advance = max(round(font.getlength(c)) for c in '0123456789') + 8
    glyphs = []
    for char in chars:
        canvas = Image.new('L', (advance, bottom - top), 255)
        draw = ImageDraw.Draw(canvas)
        draw.text(((advance - font.getlength(char)) / 2, -top), char, font=font, fill=0)
        glyphs.append(canvas)
    header = prelude('NekoClockAssets')
    for label, width, height in [('Large',80,172), ('Small',24,36)]:
        header += f'constexpr int {label}W = {width}, {label}H = {height};\n'
        for i, glyph in enumerate(glyphs):
            im = binary(glyph.resize((width, height), Image.Resampling.LANCZOS))
            header += array(f'{label}{i}', xbm(im))
        header += f'inline const uint8_t *const {label}[11] = {{' + ','.join(f'{label}{i}' for i in range(11)) + '};\n'
    (ROOT / 'NekoClockAssets.h').write_text(header + '}\n')
    preview = Image.new('1', (400, 230), 1)
    for value, x in zip([1,8,4,8],[12,98,222,308]):
        im = binary(glyphs[value].resize((80,172), Image.Resampling.LANCZOS))
        preview.paste(im, (x,30))
    draw = ImageDraw.Draw(preview)
    draw.rectangle((197,86,204,96),fill=0); draw.rectangle((197,139,204,149),fill=0)
    preview.save(ASSETS / 'orbitron/clock-preview.png')


def web():
    png = (ASSETS / 'pixel-neko/pet-atlas.png').read_bytes()
    ttf = (ASSETS / 'orbitron/Orbitron.ttf').read_bytes()
    header = prelude('NekoWebAssets') + array('PetPng',png) + array('OrbitronTtf',ttf) + '}\n'
    (ROOT / 'NekoWebAssets.h').write_text(header)


def brand():
    source=Image.open(ASSETS/'brand/polyNERO.png').convert('RGBA')
    white=Image.new('RGBA',source.size,'white');white.alpha_composite(source)
    gray=white.convert('L')
    bounds=gray.point(lambda p:255 if p<128 else 0).getbbox()
    crop=gray.crop(bounds)
    height=round(crop.height*160/crop.width)
    logo=Image.new('L',(160,40),255)
    logo.paste(crop.resize((160,height),Image.Resampling.LANCZOS),(0,(40-height)//2))
    logo=binary(logo)
    logo.save(ASSETS/'brand/logo-display.png')
    (ROOT/'NekoBrandAssets.h').write_text(prelude('NekoBrandAssets')+array('Logo',xbm(logo))+'}\n')


if __name__ == '__main__':
    pets(); clocks(); web(); brand()
    print('Packed: one coherent base at 64/128/160/192/224 px, Orbitron glyphs and offline web assets.')
